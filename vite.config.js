import { defineConfig } from 'vite';
import laravel from 'laravel-vite-plugin';
import tailwindcss from '@tailwindcss/vite';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, resolve } from 'node:path';
import rtlcss from 'rtlcss';

/**
 * Right-to-left copies of the public site's stylesheets, served to Arabic
 * instead of the originals (layouts/partials/head.blade.php). Each copy
 * carries its source's sha1, so a test fails when one falls behind.
 */
const rtlStylesheetCopies = {
    'public/assets/css/vendor/vendor.min.css': 'public/assets/css/vendor/vendor.rtl.min.css',
    'public/assets/css/style.css': 'public/assets/css/style.rtl.css',
    'public/assets/css/custom.css': 'public/assets/css/custom.rtl.css',
};

function writeRtlCopy(source) {
    const css = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
    const sourceSha1 = createHash('sha1').update(css).digest('hex');
    const banner = `/* Right-to-left copy of ${basename(source)}, generated by rtlcss (vite.config.js). Do not edit. source-sha1: ${sourceSha1} */\n`;

    // @charset has to stay the first statement in the file.
    const mirrored = rtlcss.process(css).replace(/^(@charset [^;]+;\n?)?/, (charset) => charset + banner);

    writeFileSync(rtlStylesheetCopies[source], mirrored);
}

/**
 * Regenerates the copies on every build, when `npm run dev` starts, and
 * whenever a source changes while it runs.
 */
function rtlStylesheets() {
    const sources = Object.keys(rtlStylesheetCopies);

    return {
        name: 'rtl-stylesheets',
        buildStart() {
            sources.forEach(writeRtlCopy);
        },
        configureServer(server) {
            server.watcher.add(sources);
            server.watcher.on('change', (file) => {
                const source = sources.find((path) => resolve(path) === resolve(file));

                if (source) {
                    writeRtlCopy(source);
                }
            });
        },
    };
}

export default defineConfig({
    plugins: [
        laravel({
            input: [
                'resources/css/app.css',
                'resources/js/app.js',
                'resources/css/admin.css',
                'resources/js/admin.js',
            ],
            refresh: true,
        }),
        tailwindcss(),
        rtlStylesheets(),
    ],
});
